# Lebedev grids for md_mbis (src/md_mbis_lebedev.inl), from PySCF's tables reduced to their octahedral orbits: one
# canonical point (a >= b >= c >= 0) and the weight of each, from which the full grid is the orbit under permutations
# and sign changes. Every grid is checked by regenerating it and comparing monomial integrals. Needs pyscf.
import numpy as np, itertools
from pyscf.dft import gen_grid
orders = [11, 17, 23, 29, 35, 41, 47, 53, 59]
def orbit(a, b, c):
    pts = set()
    for p in itertools.permutations((a, b, c)):
        for s in itertools.product((1, -1), repeat=3):
            pts.add(tuple(round(v * si, 15) + 0.0 for v, si in zip(p, s)))
    return np.array(sorted(pts))
out = []
OUT = __import__("os").path.join(__import__("os").path.dirname(__file__), "..", "src", "md_mbis_lebedev.inl")
for L in orders:
    n = gen_grid.LEBEDEV_ORDER[L]
    g = gen_grid.MakeAngularGrid(n)
    xyz, w = g[:, :3], g[:, 3]
    canon = {}
    for p, wi in zip(xyz, w):
        key = tuple(np.round(sorted(np.abs(p), reverse=True), 12))
        canon.setdefault(key, []).append(wi)
    gens = []
    for key, ws in canon.items():
        assert np.ptp(ws) < 1e-13 * max(1, abs(ws[0])), (L, key, np.ptp(ws))
        gens.append((key, ws[0], len(ws)))
    gens.sort(key=lambda t: (-t[0][0], -t[0][1], -t[0][2]))
    # regenerate and compare
    rx = np.concatenate([orbit(*k) for k, _, _ in gens]); rw = np.concatenate([np.full(len(orbit(*k)), wgt) for k, wgt, _ in gens])
    assert len(rx) == n and all(len(orbit(*k)) == m for k, _, m in gens), (L, len(rx), n)
    # exactness on monomials up to degree L
    err = 0
    for i in range(L + 1):
        for j in range(L + 1 - i):
            for k in range(L + 1 - i - j):
                f = (rx[:, 0] ** i * rx[:, 1] ** j * rx[:, 2] ** k * rw).sum()
                g2 = (xyz[:, 0] ** i * xyz[:, 1] ** j * xyz[:, 2] ** k * w).sum()
                err = max(err, abs(f - g2))
    print("order %2d: %4d points, %2d orbits, weight sum %.15f, max monomial diff vs pyscf %.1e" % (L, n, len(gens), rw.sum(), err))
    out.append((L, n, gens))
with open(OUT, "w") as f:
    f.write("// Lebedev grids, generated by tools/gen_mbis_lebedev.py from PySCF's tables (Lebedev and Laikov, Dokl. Math. 59, 477 (1999)):\n")
    f.write("// per grid its orbits under the octahedral group, each as one point a >= b >= c >= 0 and the weight of every point\n")
    f.write("// of the orbit (the weights of a grid summing to 1). mbis_lebedev_init expands them.\n")
    for L, n, gens in out:
        f.write("static const double mbis_lebedev_%d[][4] = {\n" % L)
        for (a, b, c), wgt, m in gens:
            f.write("    {%.17g, %.17g, %.17g, %.17g},\n" % (a, b, c, wgt))
        f.write("};\n")
    f.write("static const struct { uint32_t order, num_points, num_orbits; const double (*orbit)[4]; } mbis_lebedev[] = {\n")
    for L, n, gens in out:
        f.write("    {%d, %d, %d, mbis_lebedev_%d},\n" % (L, n, len(gens), L))
    f.write("};\n")
